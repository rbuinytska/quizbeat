// Search songs using Apple iTunes Search API (Returns 30-sec previews, high-res artwork, years)
export async function searchTracksOnline(query) {
  if (!query || query.trim().length === 0) return [];

  const url = `https://itunes.apple.com/search?term=${encodeURIComponent(query)}&media=music&entity=song&limit=25`;
  const res = await fetch(url);
  if (!res.ok) throw new Error('Ошибка поиска треков');

  const data = await res.json();
  return (data.results || [])
    .filter(item => item.previewUrl)
    .map(item => ({
      id: `itunes_${item.trackId}`,
      name: item.trackName,
      artist: item.artistName,
      albumArt: (item.artworkUrl100 || '').replace('100x100bb', '600x600bb'),
      year: item.releaseDate ? item.releaseDate.substring(0, 4) : '—',
      audioUrl: item.previewUrl,
      source: 'preview'
    }));
}

// HTML5 Audio Controller for 30s previews
class PreviewPlayerService {
  constructor() {
    this.audio = new Audio();
    this.audio.preload = 'auto';
    this.timeoutId = null;
    this.onEndedCallback = null;
  }

  play(audioUrl, durationSeconds = 10, onEnded = null) {
    this.stop();
    this.onEndedCallback = onEnded;

    this.audio.src = audioUrl;
    this.audio.currentTime = 0;

    const playPromise = this.audio.play();
    if (playPromise !== undefined) {
      playPromise
        .then(() => {
          if (durationSeconds && durationSeconds > 0) {
            this.timeoutId = setTimeout(() => {
              this.stop();
              if (this.onEndedCallback) this.onEndedCallback();
            }, durationSeconds * 1000);
          }
        })
        .catch(err => {
          console.warn('Playback interrupted or blocked by browser autoplay:', err);
        });
    }

    this.audio.onended = () => {
      this.stop();
      if (this.onEndedCallback) this.onEndedCallback();
    };
  }

  stop() {
    if (this.timeoutId) {
      clearTimeout(this.timeoutId);
      this.timeoutId = null;
    }
    if (this.audio) {
      this.audio.pause();
    }
  }

  pause() {
    if (this.timeoutId) {
      clearTimeout(this.timeoutId);
    }
    this.audio.pause();
  }

  resume(remainingSeconds) {
    this.audio.play();
    if (remainingSeconds > 0) {
      this.timeoutId = setTimeout(() => {
        this.stop();
        if (this.onEndedCallback) this.onEndedCallback();
      }, remainingSeconds * 1000);
    }
  }

  setVolume(vol) {
    this.audio.volume = Math.max(0, Math.min(1, vol));
  }
}

